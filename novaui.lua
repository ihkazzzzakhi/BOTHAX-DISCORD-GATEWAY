  if max <= min then error('RangeSlider: max harus > min', 3) end
  local function one(v)
    return tonumber(Util.fmt(Util.clamp(Util.snap(v, min, step), min, max), step))
  end
  local function norm(v)
    if type(v) ~= 'table' or type(v[1]) ~= 'number' or type(v[2]) ~= 'number' then return nil end
    local a, b = one(v[1]), one(v[2])
    if a > b then a, b = b, a end
    return { a, b }
  end
  local d = o.default or { min, max }
  local cb = o.callback and function(v) o.callback(v[1], v[2]) end or nil
  local it = { comp = C, id = o.id, name = o.name or o.id, min = min, max = max,
               step = step, unit = o.unit or '', one = one }
  sec.ui.state:define(o.id, norm(d) or { min, max }, cb, norm)
  sec.items[#sec.items + 1] = it
end

local function pct(it, v) return (v - it.min) / (it.max - it.min) * 100 end
local function label(it, v)
  return Util.fmt(v[1], it.step) .. ' - ' .. Util.fmt(v[2], it.step) .. it.unit
end

function C.render(it, v)
  local a, b = pct(it, v[1]), pct(it, v[2])
  return string.format(
    '<div class="nv-row2"><div class="nv-line"><span class="nv-name">%s</span>' ..
    '<span class="nv-val" id="sv-%s">%s</span></div>' ..
    '<div class="nv-trk" id="st-%s"><div class="nv-bar"></div>' ..
    '<div class="nv-fill" id="sf-%s" style="left: %.2f%%; width: %.2f%%;"></div>' ..
    '<div class="nv-th" id="sh-%s-1" style="left: %.2f%%;"><div class="nv-dot"></div></div>' ..
    '<div class="nv-th" id="sh-%s-2" style="left: %.2f%%;"><div class="nv-dot"></div></div></div></div>',
    Util.esc(it.name), it.id, Util.esc(label(it, v)), it.id, it.id, a, b - a, it.id, a, it.id, b)
end

function C.bind(doc, it, ui)
  local trk, fill, val = doc:GetElementById('st-' .. it.id), doc:GetElementById('sf-' .. it.id), doc:GetElementById('sv-' .. it.id)
  local th = { doc:GetElementById('sh-' .. it.id .. '-1'), doc:GetElementById('sh-' .. it.id .. '-2') }
  if not (trk and fill and val and th[1] and th[2]) then return end
  local state, span = ui.state, it.max - it.min

  local function paint(v)
    local a, b = pct(it, v[1]), pct(it, v[2])
    fill.style.left = string.format('%.2f%%', a)
    fill.style.width = string.format('%.2f%%', b - a)
    th[1].style.left = string.format('%.2f%%', a)
    th[2].style.left = string.format('%.2f%%', b)
    val.inner_rml = Util.esc(label(it, v))
  end
  ui._paint[it.id] = paint

  for k = 1, 2 do
    local on, x0, v0, last = false, 0, 0, 0
    Backend.on(th[k], 'dragstart', function(ev)
      on = true
      x0 = ev.parameters['mouse_x'] or 0
      v0 = state:get(it.id)[k]
      last = v0
    end)
    Backend.on(th[k], 'drag', function(ev)
      if not on then return end
      local w = trk.offset_width
      if not w or w <= 0 then return end
      local cur = state:get(it.id)
      local nv = it.one(v0 + ((ev.parameters['mouse_x'] or x0) - x0) / w * span)
      if k == 1 then nv = math.min(nv, cur[2]) else nv = math.max(nv, cur[1]) end
      if nv == last or math.abs(nv - last) > span * 0.5 then return end
      last = nv
      local out = { cur[1], cur[2] }
      out[k] = nv
      paint(out)
      state:set(it.id, out, true)
    end)
    Backend.on(th[k], 'dragend', function()
      on = false
      state:touch(it.id)
    end)
  end
end

return C

end

