function C.add(sec, o)
  Util.checkId(o.id, 'Slider')
  local min, max, step = o.min or 0, o.max or 100, o.step or 1
  if max <= min then error('Slider: max harus > min', 3) end
  local function norm(v)
    if type(v) ~= 'number' then return nil end
    return tonumber(Util.fmt(Util.clamp(Util.snap(v, min, step), min, max), step))
  end
  local it = { comp = C, id = o.id, name = o.name or o.id, min = min, max = max,
               step = step, unit = o.unit or '', norm = norm }
  sec.ui.state:define(o.id, norm(o.default or min), o.callback, norm)
  sec.items[#sec.items + 1] = it
end

function C.render(it, value)
  local p = (value - it.min) / (it.max - it.min) * 100
  return string.format(
    '<div class="nv-row2"><div class="nv-line"><span class="nv-name">%s</span>' ..
    '<span class="nv-val" id="sv-%s">%s</span></div>' ..
    '<div class="nv-trk" id="st-%s"><div class="nv-bar"></div>' ..
    '<div class="nv-fill" id="sf-%s" style="width: %.2f%%;"></div>' ..
    '<div class="nv-th" id="sh-%s" style="left: %.2f%%;"><div class="nv-dot"></div></div></div></div>',
    Util.esc(it.name), it.id, Util.esc(Util.fmt(value, it.step) .. it.unit), it.id, it.id, p, it.id, p)
end

function C.bind(doc, it, ui)
  local trk, fill = doc:GetElementById('st-' .. it.id), doc:GetElementById('sf-' .. it.id)
  local th, val = doc:GetElementById('sh-' .. it.id), doc:GetElementById('sv-' .. it.id)
  if not (trk and fill and th and val) then return end
  local state, span = ui.state, it.max - it.min

  local function paint(v)
    local p = string.format('%.2f%%', (v - it.min) / span * 100)
    fill.style.width = p
    th.style.left = p
    val.inner_rml = Util.esc(Util.fmt(v, it.step) .. it.unit)
  end
  ui._paint[it.id] = paint

  local on, x0, v0, last = false, 0, 0, 0
  Backend.on(th, 'dragstart', function(ev)
    on = true
    x0 = ev.parameters['mouse_x'] or 0
    v0 = state:get(it.id)
    last = v0
  end)
  Backend.on(th, 'drag', function(ev)
    if not on then return end
    local w = trk.offset_width
    if not w or w <= 0 then return end
    local nv = it.norm(v0 + ((ev.parameters['mouse_x'] or x0) - x0) / w * span)
    if nv == nil or nv == last then return end
    if math.abs(nv - last) > span * 0.5 then return end   -- koordinat ngaco
    last = nv
    paint(nv)
    state:set(it.id, nv, true)       -- simpan nanti, saat dragend
  end)
  Backend.on(th, 'dragend', function()
    on = false
    state:touch(it.id)
  end)
end

return C

end

