    '<span class="nv-brand">', Util.esc(self.opts.title), '</span></div>',
    '<div class="nv-x" id="nv-x">×</div></div>\n',
    '<div class="nv-body">\n<div class="nv-side">', table.concat(tabs), '</div>\n',
    '<div class="nv-main">', table.concat(pages), '</div>\n</div>\n</div>\n</body>\n</rml>\n',
  })
end

function Nova:_bind(doc)
  self._paint = {}
  local tabs, pages = {}, {}
  for i = 1, #self.cats do
    tabs[i] = doc:GetElementById('nv-tab-' .. i)
    pages[i] = doc:GetElementById('nv-page-' .. i)
  end
  for i = 1, #self.cats do
    Backend.on(tabs[i], 'click', function()
      for j = 1, #tabs do
        tabs[j]:SetClass('on', j == i)
        pages[j]:SetClass('on', j == i)
      end
    end)
  end
  for _, cat in ipairs(self.cats) do
    for _, sec in ipairs(cat.sections) do
      for _, it in ipairs(sec.items) do
        if it.comp.bind then it.comp.bind(doc, it, self) end
      end
    end
  end
  Backend.on(doc:GetElementById('nv-x'), 'click', function() self:Hide() end)
end

