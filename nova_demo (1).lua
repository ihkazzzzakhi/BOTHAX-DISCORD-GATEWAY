-- coba satu folder: tulis font + RCSS + RML, lalu muat dokumen
function Nova:_open(dir)
  local okF, info = Storage.ensureFont(dir, FONT_FILE)
  if not okF then Backend.log('FONT: ' .. tostring(info)); return false end
  local fontOk = Backend.loadFont(dir .. FONT_FILE)
  if fontOk == false then
    Backend.log('LoadFontFace mengembalikan false: bisa berarti family "NovaSans" sudah terdaftar (aman), atau file tidak terbaca di ' .. dir)
  end

  local rcss = Theme.apply(RCSS, self.opts.theme)
  local rcssFile = 'nova_' .. Storage.hash(rcss) .. '.rcss'
  local rmlFile = 'nova_' .. self.docName .. '.rml'
  local ok, err = Storage.write(dir .. rcssFile, rcss)
  if ok then ok, err = Storage.write(dir .. rmlFile, self:_rml(rcssFile)) end
  if not ok then Backend.log('gagal menulis di ' .. dir .. ': ' .. tostring(err)); return false end

  local doc = Backend.load(self.docName, dir .. rmlFile)
  if not doc then Backend.log('LoadDocument gagal di ' .. dir); return false end
  self.doc, self.dir, self._probed = doc, dir, false

  local win = doc:GetElementById('nv-win')
  Layout.apply(win, self.pos)
  self:_bind(doc)
  Drag.attach(doc:GetElementById('nv-top'), win, self.pos)
  Layout.watch(doc, win, self.pos)

  -- Semua listener dipasang di dokumen ini saja (hilang bersama dokumennya),
  -- jadi menjalankan script berulang kali tidak meninggalkan referensi basi.
  Backend.on(doc, 'mousedown', function()
    self:_probeFont()
    pcall(function() doc:PullToFront() end)
  end)
  Backend.log('UI dimuat dari ' .. dir)
  return true
end

-- Teks yang tidak ter-render lebarnya 0: ini cara paling jujur untuk tahu font terdaftar atau tidak.
function Nova:_probeFont()
  if self._probed or not self.doc then return end
  local el = self.doc:GetElementById('nv-probe')
  if not el then return end
  self._probed = true
  local w = el.offset_width
  if w and w > 0 then
    Backend.log('probe font: OK (lebar teks uji = ' .. tostring(w) .. ')')
  else
    Backend.log('probe font: GAGAL (lebar teks uji = ' .. tostring(w) .. '). Family "NovaSans" belum terdaftar: restart game lalu jalankan lagi.')
  end
  self:_writeReport()
end

function Nova:_diag(tried, dirs)
  Backend.log('Nova v' .. Nova.version .. ' | tema ' .. self.opts.theme)
  Backend.log('folder dicoba: ' .. table.concat(tried, ' | '))
  Backend.log('folder bisa ditulis: ' .. table.concat(dirs, ' | '))
  Backend.log('os.execute: ' .. type(os and os.execute) .. ' | GetWorkingPath: ' .. type(GetWorkingPath) ..
    ' | ImGui.SetClipboard: ' .. type(ImGui and ImGui.SetClipboard))
end

-- Laporan ditulis ke folder media (bisa dibuka lewat file manager) dan, bila debug=true, disalin ke clipboard.
function Nova:_writeReport()
  local text = Backend.report()
  local ok = Storage.write('/sdcard/Android/media/' .. Storage.package() .. '/nova_debug.txt', text)
  if not ok and (self.dir or self._dir) then Storage.write((self.dir or self._dir) .. 'nova_debug.txt', text) end
  if self.opts.debug and ImGui and ImGui.SetClipboard then pcall(ImGui.SetClipboard, text) end
end

function Nova:Show()
  if self.doc then return true end
  Backend.init()
  local tried = Storage.candidates(self.opts.dir)
  local dirs = Storage.writableDirs(tried)
  if #dirs == 0 then
    Backend.log('tidak ada folder yang bisa ditulis. Dicoba: ' .. table.concat(tried, ' | '))
    return false
  end
  self:_diag(tried, dirs)
  self._dir = dirs[1]                      -- config selalu di folder tulis pertama
  if self.opts.config and not self._configLoaded then
    self._configLoaded = true
    self:_loadConfig()
  end
  for _, d in ipairs(dirs) do
    if self:_open(d) then self:_writeReport(); return true end
  end
  Backend.log('LoadDocument gagal di semua folder')
  self:_writeReport()
  return false
end

function Nova:Hide()
  if not self.doc then return end
  local doc = self.doc
  self.doc = nil
  doc:Close()
end

function Nova:IsVisible() return self.doc ~= nil end

function Nova:SetTheme(name)
  if not Theme.tokens[name] then error('tema tidak dikenal: ' .. tostring(name), 2) end
  if name == self.opts.theme then return end
  if not self.doc then self.opts.theme = name; return end
  -- ditunda ke frame berikutnya: aman dipanggil dari callback komponen
  Backend.defer(function()
    self:Hide()
    self.opts.theme = name
    self:Show()
  end)
end

return Nova

