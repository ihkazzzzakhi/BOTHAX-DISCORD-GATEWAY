__M['nova.core.Storage'] = function(require)
-- Semua urusan file: pilih folder data, tulis/baca, font tertanam.
-- Folder dicoba berurutan; yang dipakai adalah yang bisa ditulis DAN bisa memuat dokumen RML
-- (pengecekan terakhir ada di NovaUI:Show).
local Base64   = require('nova.core.Base64')
local FontData = require('nova.core.FontData')
local Storage = {}

local DEFAULT_PKG = 'com.rtsoft.growtopia'   -- hanya untuk menebak lokasi folder

function Storage.package()
  if GetWorkingPath then
    local ok, p = pcall(GetWorkingPath)
    if ok and type(p) == 'string' then
      local m = p:match('/Android/media/([^/]+)') or p:match('/data/data/([^/]+)')
      if m then return m end
    end
  end
  return DEFAULT_PKG
end

local function slash(d) return (d:sub(-1) == '/') and d or (d .. '/') end

-- dir: nil (otomatis) | string | daftar string
function Storage.candidates(dir)
  if type(dir) == 'string' then return { slash(dir) } end
  if type(dir) == 'table' then
    local r = {}
    for _, d in ipairs(dir) do r[#r + 1] = slash(d) end
    return r
  end
  local p = Storage.package()
  return {
    '/data/data/' .. p .. '/nova/',                         -- sandbox game, subfolder sendiri
    '/data/data/' .. p .. '/',                              -- sandbox game, langsung
    '/sdcard/Android/media/' .. p .. '/scripts/',           -- cadangan terakhir (terbukti dari KazPanel)
  }
end

function Storage.write(path, data)
  local f, err = io.open(path, 'wb')
  if not f then return false, err end
  f:write(data)
  f:close()
  return true
end

function Storage.read(path)
  local f = io.open(path, 'rb')
  if not f then return nil end
  local d = f:read('a')
  f:close()
  return d
end

local function probe(dir)
  local p = dir .. 'nova_probe.tmp'
  if not Storage.write(p, 'ok') then return false end
  if os and os.remove then pcall(os.remove, p) end
  return true
end

local function mkdir(dir)
  if os and os.execute and dir:match('^[%w%._%-/]+$') then   -- hanya path aman untuk shell
    pcall(os.execute, 'mkdir -p "' .. dir .. '"')
  end
end

-- hanya folder yang benar-benar bisa ditulis, urutan dipertahankan
function Storage.writableDirs(list)
  local out = {}
  for _, d in ipairs(list) do
    if probe(d) then out[#out + 1] = d
    else
      mkdir(d)
      if probe(d) then out[#out + 1] = d end
    end
  end
  return out
end

-- djb2 32-bit: nama RCSS ikut isi, supaya cache stylesheet RmlUi tidak memakai versi lama
function Storage.hash(s)
  local h = 5381
  for i = 1, #s do h = (h * 33 + s:byte(i)) & 0xffffffff end
  return string.format('%08x', h)
end

local MAGIC = { ['\0\1\0\0'] = true, ['true'] = true, ['OTTO'] = true }
function Storage.isFont(b)
  return type(b) == 'string' and #b > 1000 and MAGIC[b:sub(1, 4)] == true
end

-- return true, 'ada' | 'ditulis'   atau   false, alasan
function Storage.ensureFont(dir, name)
  if Storage.isFont(Storage.read(dir .. name)) then return true, 'ada' end
  local bytes = Base64.decode(FontData)
  if not Storage.isFont(bytes) then return false, 'data font tertanam rusak' end
  local ok, err = Storage.write(dir .. name, bytes)
  if not ok then return false, 'gagal menulis ' .. dir .. name .. ': ' .. tostring(err) end
  return true, 'ditulis'
end

return Storage

end

__M['nova.core.State'] = function(require)
-- Nilai semua opsi + callback + validasi (spec) per opsi.
local Json = require('nova.util.Json')
local State = {}
State.__index = State

function State.new()
  return setmetatable({ v = {}, cb = {}, spec = {}, order = {} }, State)
end

-- spec(value) -> nilai valid atau nil
function State:define(id, default, cb, spec)
  if self.spec[id] then error('id sudah dipakai: ' .. id, 3) end
  self.v[id], self.cb[id], self.spec[id] = default, cb, spec
  self.order[#self.order + 1] = id
end

function State:get(id) return self.v[id] end

function State:valid(id, value)
  local spec = self.spec[id]
  if not spec then return nil, 'id tidak dikenal: ' .. tostring(id) end
  local nv = spec(value)
  if nv == nil then return nil, 'nilai tidak valid untuk "' .. id .. '"' end
  return nv
end

-- simpan (onChange) dulu, callback paling akhir
function State:set(id, value, noSave)
  self.v[id] = value
  if not noSave and self.onChange then self.onChange(id) end
  local cb = self.cb[id]
  if cb then
    local ok, err = pcall(cb, value)
    if not ok then (LogToConsole or print)('[Nova] callback "' .. id .. '" error: ' .. tostring(err)) end
  end
end

function State:touch(id) if self.onChange then self.onChange(id) end end

function State:all()
  local t = {}
  for _, id in ipairs(self.order) do t[id] = self.v[id] end
  return t
end

-- terapkan map dari config; callback dipanggil hanya untuk nilai yang berbeda
function State:load(map)
  local ids = {}
  for id in pairs(map) do ids[#ids + 1] = id end
  table.sort(ids)
  for _, id in ipairs(ids) do
    local spec = self.spec[id]
    if spec then
      local nv = spec(map[id])
      if nv ~= nil and Json.encode(nv) ~= Json.encode(self.v[id]) then self:set(id, nv, true) end
    end
  end
end

return State

end

