-- Nova UI (bundle) - dibuat oleh tools/bundle.lua, jangan diedit manual.
local __M, __L = {}, {}
local function require(name)
  local v = __L[name]
  if v == nil then
    local f = __M[name]
    if not f then error('modul tidak ditemukan: ' .. name, 2) end
    v = f(require)
    if v == nil then v = true end
    __L[name] = v
  end
  return v
end

__M['nova.util.Json'] = function(require)
-- JSON minimal (cukup untuk config: boolean, angka, string, array, objek).
local Json = {}

local ESC = { ['"'] = '\\"', ['\\'] = '\\\\', ['\n'] = '\\n', ['\r'] = '\\r', ['\t'] = '\\t' }
local function str(s)
  return '"' .. s:gsub('[%c"\\]', function(c) return ESC[c] or string.format('\\u%04x', c:byte()) end) .. '"'
end

function Json.encode(v)
  local t = type(v)
  if t == 'nil' then return 'null'
  elseif t == 'boolean' then return tostring(v)
  elseif t == 'number' then
    if v ~= v or v == math.huge or v == -math.huge then return 'null' end
    if v == math.floor(v) and math.abs(v) < 1e15 then return string.format('%d', v) end
    return string.format('%.14g', v)
  elseif t == 'string' then return str(v)
  elseif t == 'table' then
    if #v > 0 or next(v) == nil then
      local o = {}
      for i = 1, #v do o[i] = Json.encode(v[i]) end
      return '[' .. table.concat(o, ',') .. ']'
    end
    local keys = {}
    for k in pairs(v) do keys[#keys + 1] = tostring(k) end
    table.sort(keys)
    local o = {}
    for _, k in ipairs(keys) do o[#o + 1] = str(k) .. ':' .. Json.encode(v[k]) end
    return '{' .. table.concat(o, ',') .. '}'
  end
  error('tipe tidak didukung: ' .. t)
end

local UNESC = { n = '\n', t = '\t', r = '\r', b = '\b', f = '\f', ['"'] = '"', ['\\'] = '\\', ['/'] = '/' }

-- return nilai, atau nil + pesan error
function Json.decode(s)
  local pos = 1
  local function fail(m) error('json: ' .. m .. ' (posisi ' .. pos .. ')', 0) end
  local function ws() pos = s:find('%S', pos) or (#s + 1) end
  local val

  local function lit(word, v)
    if s:sub(pos, pos + #word - 1) ~= word then fail('token tidak dikenal') end
    pos = pos + #word
    return v
  end

  local function strv()
    pos = pos + 1
    local out = {}
    while true do
      local c = s:sub(pos, pos)
      if c == '' then fail('string tidak selesai') end
      if c == '"' then pos = pos + 1; return table.concat(out) end
      if c == '\\' then
        local n = s:sub(pos + 1, pos + 1)
        if n == 'u' then
          local cp = tonumber(s:sub(pos + 2, pos + 5), 16)
          if not cp then fail('escape \\u rusak') end
          out[#out + 1] = utf8.char(cp); pos = pos + 6
        elseif UNESC[n] then out[#out + 1] = UNESC[n]; pos = pos + 2
        else fail('escape tidak dikenal') end
      else
        out[#out + 1] = c; pos = pos + 1
      end
    end
  end

  function val()
    ws()
    local c = s:sub(pos, pos)
    if c == '{' then
      pos = pos + 1
      local o = {}
      ws()
      if s:sub(pos, pos) == '}' then pos = pos + 1; return o end
      while true do
        ws()
        if s:sub(pos, pos) ~= '"' then fail('kunci harus string') end
        local k = strv()
        ws()
        if s:sub(pos, pos) ~= ':' then fail('":" hilang') end
        pos = pos + 1
        o[k] = val()
        ws()
        local d = s:sub(pos, pos); pos = pos + 1
        if d == '}' then return o elseif d ~= ',' then fail('"," atau "}" hilang') end
      end
    elseif c == '[' then
      pos = pos + 1
      local a = {}
      ws()
      if s:sub(pos, pos) == ']' then pos = pos + 1; return a end
      while true do
        a[#a + 1] = val()
        ws()
        local d = s:sub(pos, pos); pos = pos + 1
        if d == ']' then return a elseif d ~= ',' then fail('"," atau "]" hilang') end
      end
    elseif c == '"' then return strv()
    elseif c == 't' then return lit('true', true)
    elseif c == 'f' then return lit('false', false)
    elseif c == 'n' then return lit('null', nil)
    else
      local num = s:match('^-?%d+%.?%d*[eE]?[+-]?%d*', pos)
      if not num or num == '' then fail('token tidak dikenal') end
      pos = pos + #num
      return tonumber(num) or fail('angka rusak')
    end
  end

  local ok, r = pcall(function()
    local v = val()
    ws()
    if pos <= #s then fail('ada sisa teks') end
    return v
  end)
  if ok then return r end
  return nil, r
end

return Json

end

__M['nova.core.Util'] = function(require)
local Util = {}

function Util.esc(s)
  return (tostring(s):gsub('&', '&amp;'):gsub('<', '&lt;'):gsub('>', '&gt;'):gsub('"', '&quot;'))
end

function Util.clamp(v, lo, hi) return math.max(lo, math.min(hi, v)) end

function Util.snap(v, min, step)
  if not step or step <= 0 then return v end
  return min + math.floor((v - min) / step + 0.5) * step
end

function Util.decimals(step)
  local s = string.format('%.6f', step):gsub('0+$', ''):gsub('%.$', '')
  local d = s:match('%.(%d+)$')
  return d and #d or 0
end

function Util.fmt(v, step)
  return string.format('%.' .. Util.decimals(step or 1) .. 'f', v)
end

function Util.indexOf(list, v)
  for i, x in ipairs(list) do if x == v then return i end end
end

function Util.checkId(id, what)
  if type(id) ~= 'string' or not id:match('^[%w_%-]+$') then
    error(what .. ': id wajib string [A-Za-z0-9_-]', 3)
  end
end

function Util.checkOptions(options, what)
  if type(options) ~= 'table' or #options == 0 then error(what .. ': options harus array tidak kosong', 3) end
  for _, o in ipairs(options) do
    if type(o) ~= 'string' then error(what .. ': semua options harus string', 3) end
  end
end

return Util

end

__M['nova.core.Base64'] = function(require)
local Base64 = {}
local B = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
local REV = {}
for i = 1, 64 do REV[B:byte(i)] = i - 1 end

function Base64.decode(s)
  local out, n, acc, bits = {}, 0, 0, 0
  for i = 1, #s do
    local v = REV[s:byte(i)]          -- spasi, baris baru, '=' diabaikan
    if v then
      acc = (acc << 6) | v
      bits = bits + 6
      if bits >= 8 then
        bits = bits - 8
        n = n + 1
        out[n] = string.char((acc >> bits) & 0xFF)
        acc = acc & ((1 << bits) - 1)
      end
    end
  end
  return table.concat(out)
end

return Base64

end

