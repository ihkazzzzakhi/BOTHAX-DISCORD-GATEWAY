__M['nova.rml.Backend'] = function(require)
-- SATU-SATUNYA file yang menyentuh API rmlui Bothax (API yang terbukti jalan di loader KazPanel).
local Backend = {}
local ctx

Backend.buf = {}
function Backend.log(msg)
  local line = '[Nova] ' .. tostring(msg)
  Backend.buf[#Backend.buf + 1] = line
  if #Backend.buf > 300 then table.remove(Backend.buf, 1) end
  local out = LogToConsole or print   -- cadangan bila LogToConsole tidak ada
  out(line)
end

function Backend.report() return table.concat(Backend.buf, '\n') end

function Backend.init()
  ctx = rmlui and rmlui.contexts and rmlui.contexts[1]
  if not ctx then error('rmlui.contexts[1] tidak ada', 2) end
  return ctx
end

function Backend.loadFont(path)
  local ok = rmlui.LoadFontFace(path, false, 0)
  -- false bisa berarti family sudah terdaftar sebelumnya di sesi game ini
  Backend.log('LoadFontFace(' .. path .. ') -> ' .. tostring(ok))
  return ok
end

function Backend.load(name, path)
  local old = ctx.documents[name]
  if old then old:Close() end
  local doc = ctx:LoadDocument(path)
  if not doc then return nil end
  doc:Show()
  return doc
end

function Backend.dpRatio() return ctx.dp_ratio or 1 end

-- ukuran layar dalam dp (ctx.dimensions dalam px)
function Backend.screenDp()
  local r = Backend.dpRatio()
  return ctx.dimensions.x / r, ctx.dimensions.y / r
end

function Backend.rect(el, x, y, w, h)
  local s = el.style
  if x then s.left = string.format('%.1fdp', x) end
  if y then s.top = string.format('%.1fdp', y) end
  if w then s.width = string.format('%.1fdp', w) end
  if h then s.height = string.format('%.1fdp', h) end
end

function Backend.on(target, event, fn) target:AddEventListener(event, fn, false) end
function Backend.onContext(event, fn) ctx:AddEventListener(event, fn, false) end

-- jalankan fn di frame berikutnya (aman dipakai dari dalam event handler dokumen)
local deferN = 0
function Backend.defer(fn)
  if not AddHook then return fn() end
  deferN = deferN + 1
  local id = 'nova_defer_' .. deferN
  AddHook('draw', id, function()
    if RemoveHook then RemoveHook(id) end
    fn()
  end)
end

return Backend

end

__M['nova.rml.Layout'] = function(require)
-- Ukuran & posisi window mengikuti layar (satuan dp).
local Backend = require('nova.rml.Backend')
local Layout = {}

local function clamp(v, lo, hi) return math.max(lo, math.min(v, hi)) end

function Layout.compute()
  local sw, sh = Backend.screenDp()
  local w = math.min(sw, math.min(720, math.max(300, sw * 0.92)))
  local h = math.min(sh, math.min(460, math.max(260, sh * 0.85)))
  return { sw = sw, sh = sh, w = w, h = h, compact = w < 560 }
end

function Layout.clampPos(pos)
  local sw, sh = Backend.screenDp()
  pos.x = clamp(pos.x, 0, math.max(0, sw - (pos.w or 0)))
  pos.y = clamp(pos.y, 0, math.max(0, sh - (pos.h or 0)))
end

-- pos.x kosong = pertama kali -> di tengah
function Layout.apply(win, pos)
  local L = Layout.compute()
  pos.w, pos.h = L.w, L.h
  if not pos.x then pos.x, pos.y = (L.sw - L.w) / 2, (L.sh - L.h) / 2 end
  Layout.clampPos(pos)
  Backend.rect(win, pos.x, pos.y, L.w, L.h)
  win:SetClass('compact', L.compact)
  return L
end

-- Tanpa hook per-frame (hook yang tertinggal setelah script dijalankan ulang bisa crash):
-- cek ukuran saat event 'resize' dan saat window disentuh. Listener ikut hilang bersama dokumen.
function Layout.watch(doc, win, pos)
  local lx, ly
  local function check()
    local sw, sh = Backend.screenDp()
    if sw ~= lx or sh ~= ly then
      lx, ly = sw, sh
      Layout.apply(win, pos)
    end
  end
  Backend.on(doc, 'resize', check)
  Backend.on(win, 'mousedown', check)
  check()
end

return Layout

end

__M['nova.rml.Drag'] = function(require)
-- Geser window lewat handle (title bar). Posisi disimpan sendiri dalam dp.
local Backend = require('nova.rml.Backend')
local Layout = require('nova.rml.Layout')
local Drag = {}

function Drag.attach(handle, win, pos)
  local dragging = false
  local mx0, my0, x0, y0, lx, ly = 0, 0, 0, 0, 0, 0

  Backend.on(handle, 'dragstart', function(ev)
    dragging = true
    mx0 = ev.parameters['mouse_x'] or 0
    my0 = ev.parameters['mouse_y'] or 0
    x0, y0 = pos.x, pos.y
    lx, ly = x0, y0
  end)

  Backend.on(handle, 'drag', function(ev)
    if not dragging then return end
    local r = Backend.dpRatio()
    local nx = x0 + ((ev.parameters['mouse_x'] or mx0) - mx0) / r
    local ny = y0 + ((ev.parameters['mouse_y'] or my0) - my0) / r
    -- event terakhir saat jari dilepas kadang membawa koordinat ngaco: abaikan
    if math.abs(nx - lx) + math.abs(ny - ly) > 250 then return end
    pos.x, pos.y = nx, ny
    Layout.clampPos(pos)
    lx, ly = pos.x, pos.y
    Backend.rect(win, pos.x, pos.y)
  end)

  Backend.on(handle, 'dragend', function() dragging = false end)
end

return Drag

end

